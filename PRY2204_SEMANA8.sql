SELECT cod_mecanico AS "ID MECANICO",
       pnombre || ' ' || apaterno AS "NOMBRE MECANICO",
       sueldo AS "SALARIO",
       monto_impuesto AS "IMPUESTO ACTUAL",
       monto_impuesto * 0.80 AS "IMPUESTO REBAJADO",
       sueldo - (monto_impuesto * 0.80) AS "SUELDO CON REBAJA IMPUESTOS"
FROM MECANICO
WHERE bono_jefatura IS NULL
  AND monto_impuesto < 40000
ORDER BY monto_impuesto DESC, apaterno ASC;

-- Informe 2

SELECT cod_mecanico AS "IDENTIFICADOR",
       pnombre || ' ' || snombre || ' ' || apaterno AS "MECANICO",
       sueldo AS "SALARIO ACTUAL",
       sueldo * 0.05 AS "AJUSTE",
       sueldo * 1.05 AS "SUELDO_REAJUSTADO"
FROM MECANICO
WHERE sueldo BETWEEN 600000 AND 900000
   OR cod_supervisor IS NULL
ORDER BY sueldo ASC,
         (pnombre || ' ' || snombre || ' ' || apaterno) DESC;
         
         

CREATE TABLE PAIS (
    id_pais NUMBER GENERATED BY DEFAULT AS IDENTITY
        (START WITH 9 INCREMENT BY 3),
    nom_pais VARCHAR2(50) NOT NULL,
    CONSTRAINT PAIS_PK PRIMARY KEY (id_pais)
);

CREATE TABLE CIUDAD (
    id_ciudad NUMBER NOT NULL,
    nom_ciudad VARCHAR2(50) NOT NULL,
    cod_pais NUMBER NOT NULL,
    CONSTRAINT CIUDAD_PK PRIMARY KEY (id_ciudad),
    CONSTRAINT CIUDAD_PAIS_FK FOREIGN KEY (cod_pais)
        REFERENCES PAIS(id_pais)
);

CREATE TABLE SUCURSAL (
    id_sucursal VARCHAR2(3) NOT NULL,
    nom_sucursal VARCHAR2(50) NOT NULL,
    calle VARCHAR2(50) NOT NULL,
    num_calle NUMBER NOT NULL,
    cod_ciudad NUMBER NOT NULL,
    CONSTRAINT SUCURSAL_PK PRIMARY KEY (id_sucursal),
    CONSTRAINT SUCURSAL_CIUDAD_FK FOREIGN KEY (cod_ciudad)
        REFERENCES PRY2204_S8.CIUDAD(id_ciudad)
);

CREATE TABLE MECANICO (
    cod_mecanico NUMBER GENERATED BY DEFAULT AS IDENTITY
        (START WITH 460 INCREMENT BY 7),
    pnombre VARCHAR2(30) NOT NULL,
    snombre VARCHAR2(30),
    apaterno VARCHAR2(30) NOT NULL,
    amaterno VARCHAR2(30),
    bono_jefatura NUMBER,
    sueldo NUMBER NOT NULL,
    monto_impuesto NUMBER NOT NULL,
    cod_supervisor NUMBER,
    CONSTRAINT MECANICO_PK PRIMARY KEY (cod_mecanico),
    CONSTRAINT MECANICO_SUPERVISOR_FK FOREIGN KEY (cod_supervisor)
        REFERENCES PRY2204_S8.MECANICO(cod_mecanico)
);

CREATE TABLE SERVICIO (
    id_servicio NUMBER(3) NOT NULL,
    descripcion VARCHAR2(100) NOT NULL,
    costo NUMBER(7) NOT NULL,
    CONSTRAINT SERVICIO_PK PRIMARY KEY (id_servicio)
);

CREATE TABLE MARCA (
    id_marca NUMBER(2) NOT NULL,
    descripcion VARCHAR2(20) NOT NULL,
    CONSTRAINT MARCA_PK PRIMARY KEY (id_marca)
);

CREATE TABLE TIPO_AUTOMOVIL (
    id_tipo CHAR(3) NOT NULL,
    descripcion VARCHAR2(20) NOT NULL,
    CONSTRAINT TIPO_AUTOMOVIL_PK PRIMARY KEY (id_tipo)
);

CREATE TABLE MODELO (
    id_modelo NUMBER(5) NOT NULL,
    marca_id NUMBER(2) NOT NULL,
    descripcion VARCHAR2(20) NOT NULL,
    CONSTRAINT MODELO_PK PRIMARY KEY (id_modelo, marca_id),
    CONSTRAINT MODELO_MARCA_FK FOREIGN KEY (marca_id)
        REFERENCES PRY2204_S8.MARCA(id_marca)
);

CREATE TABLE CLIENTE (
    rut NUMBER(8) NOT NULL,
    dv CHAR(1) NOT NULL,
    pnombre VARCHAR2(20) NOT NULL,
    snombre VARCHAR2(20),
    apaterno VARCHAR2(20) NOT NULL,
    amaterno VARCHAR2(20),
    telefono VARCHAR2(12),
    email VARCHAR2(40),
    tipo_cli CHAR(1) NOT NULL,
    CONSTRAINT CLIENTE_PK PRIMARY KEY (rut)
);

CREATE TABLE ESTANDAR (
    rut NUMBER(8) NOT NULL,
    puntos_fidelidad NUMBER(6) NOT NULL,
    CONSTRAINT ESTANDAR_PK PRIMARY KEY (rut),
    CONSTRAINT ESTANDAR_CLIENTE_FK FOREIGN KEY (rut)
        REFERENCES PRY2204_S8.CLIENTE(rut)
);

CREATE TABLE PREMIUM (
    rut NUMBER(8) NOT NULL,
    puntos_cliente NUMBER(6) NOT NULL,
    monto_credito NUMBER(9) NOT NULL,
    CONSTRAINT PREMIUM_PK PRIMARY KEY (rut),
    CONSTRAINT PREMIUM_CLIENTE_FK FOREIGN KEY (rut)
        REFERENCES PRY2204_S8.CLIENTE(rut)
);

CREATE TABLE AUTOMOVIL (
    patente CHAR(6) NOT NULL,
    anio NUMBER(4) NOT NULL,
    num_puertas NUMBER(1) NOT NULL,
    color VARCHAR2(20) NOT NULL,
    rut_cliente NUMBER(8) NOT NULL,
    id_tipo CHAR(3) NOT NULL,
    id_modelo NUMBER(5) NOT NULL,
    marca_id NUMBER(2) NOT NULL,
    CONSTRAINT AUTOMOVIL_PK PRIMARY KEY (patente),
    CONSTRAINT AUTOMOVIL_CLIENTE_FK FOREIGN KEY (rut_cliente)
        REFERENCES PRY2204_S8.CLIENTE(rut),
    CONSTRAINT AUTOMOVIL_TIPO_FK FOREIGN KEY (id_tipo)
        REFERENCES PRY2204_S8.TIPO_AUTOMOVIL(id_tipo),
    CONSTRAINT AUTOMOVIL_MODELO_FK FOREIGN KEY (id_modelo, marca_id)
        REFERENCES PRY2204_S8.MODELO(id_modelo, marca_id)
);

CREATE TABLE MANTENCION (
    num_mantencion NUMBER(4) NOT NULL,
    cod_sucursal VARCHAR2(3) NOT NULL,
    fecha_ingreso DATE NOT NULL,
    fecha_salida DATE,
    patente_auto CHAR(6) NOT NULL,
    cod_mecanico NUMBER(5) NOT NULL,
    costo_total NUMBER(7) NOT NULL,
    estado VARCHAR2(15),

    CONSTRAINT MANTENCION_PK PRIMARY KEY (num_mantencion),

    CONSTRAINT MANTENCION_AUTOMOVIL_FK
        FOREIGN KEY (patente_auto)
        REFERENCES PRY2204_S8.AUTOMOVIL(patente),

    CONSTRAINT MANTENCION_MECANICO_FK
        FOREIGN KEY (cod_mecanico)
        REFERENCES PRY2204_S8.MECANICO(cod_mecanico),

    CONSTRAINT MANTENCION_SUCURSAL_FK
        FOREIGN KEY (cod_sucursal)
        REFERENCES PRY2204_S8.SUCURSAL(id_sucursal)
);


CREATE TABLE DETALLE_SERVICIO (
    mantencion_num NUMBER(4) NOT NULL,
    cod_servicio NUMBER(3) NOT NULL,
    descuento_serv NUMBER(4,3) NOT NULL,
    cantidad NUMBER(3) NOT NULL,

    CONSTRAINT DETALLE_SERVICIO_PK
        PRIMARY KEY (mantencion_num, cod_servicio),

    CONSTRAINT DET_SERV_FK_MANTENCION
        FOREIGN KEY (mantencion_num)
        REFERENCES PRY2204_S8.MANTENCION(num_mantencion),

    CONSTRAINT DET_SERV_FK_SERVICIO
        FOREIGN KEY (cod_servicio)
        REFERENCES PRY2204_S8.SERVICIO(id_servicio)
);

